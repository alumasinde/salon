CREATE TABLE IF NOT EXISTS settings (k VARCHAR(40) PRIMARY KEY, v VARCHAR(255) NOT NULL) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS services (
  id INT AUTO_INCREMENT PRIMARY KEY, category VARCHAR(40) NOT NULL, name VARCHAR(80) NOT NULL,
  duration VARCHAR(30) NOT NULL DEFAULT '', price INT UNSIGNED NOT NULL, sort INT NOT NULL DEFAULT 0,
  active TINYINT(1) NOT NULL DEFAULT 1, KEY (sort)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS booking_statuses (
  id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(40) NOT NULL, color VARCHAR(7) NOT NULL DEFAULT '#000000',
  sort INT NOT NULL DEFAULT 0, active TINYINT(1) NOT NULL DEFAULT 1, KEY (sort)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS bookings (
  id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(80) NOT NULL, phone VARCHAR(20) NOT NULL,
  service VARCHAR(80) NOT NULL, date DATE NOT NULL, time VARCHAR(10) NOT NULL, notes VARCHAR(300) NOT NULL DEFAULT '',
  status_id INT NOT NULL DEFAULT 1, ip VARCHAR(45) NOT NULL DEFAULT '',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, KEY (date, time), KEY (status_id), KEY (ip, created_at)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS admins (id INT AUTO_INCREMENT PRIMARY KEY, first_name VARCHAR(40) NOT NULL, last_name VARCHAR(40) NOT NULL, phone VARCHAR(20) NOT NULL, username VARCHAR(40) NOT NULL UNIQUE, pass_hash VARCHAR(255) NOT NULL) ENGINE=InnoDB
